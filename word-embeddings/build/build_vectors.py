"""Build vectors.js for the Word Embedding Space page.

Input : glove-wiki-gigaword-100.gz (GloVe 6B, 100 dimensions, Wikipedia 2014 + Gigaword 5,
        Public Domain Dedication and License), from
        https://github.com/piskvorky/gensim-data/releases/download/glove-wiki-gigaword-100/glove-wiki-gigaword-100.gz
Output: ../vectors.js with
        - the vocabulary (most frequent purely alphabetic words plus a few curated extras),
        - every vector normalised to length 1 and quantised to int8,
        - a 3D "meaning map" (t-SNE of the most frequent content words; other words are
          placed at the average position of their nearest map neighbours).

Usage : python3 build_vectors.py path/to/glove-wiki-gigaword-100.gz
Needs : numpy only. Runs in a few minutes.
"""
import base64, gzip, json, re, sys
import numpy as np

VOCAB = 6000        # most frequent alphabetic words
MAP_WORDS = 2500    # words that get a t-SNE position directly
EXTRA = """aunt uncle niece nephew grandson granddaughter mouse mice kitten puppy swim swam swimming slower smaller
tiger lion elephant giraffe zebra monkey wolf fox rabbit horse cow pig sheep goat chicken duck eagle owl shark whale dolphin
banana apple orange grape lemon strawberry cherry potato tomato carrot onion garlic bread cheese butter pizza pasta rice
violin piano guitar drum trumpet flute cello saxophone purple pink yellow brown grey gray silver golden
doctor nurse teacher lawyer engineer farmer pilot chef baker plumber carpenter scientist programmer
happy sad angry afraid surprised excited bored tired lonely proud jealous calm
madrid lisbon athens vienna warsaw prague budapest dublin oslo stockholm helsinki copenhagen brussels amsterdam
cairo nairobi delhi tokyo beijing seoul bangkok hanoi jakarta manila lima bogota santiago ottawa canberra
spain portugal greece austria poland hungary ireland norway sweden finland denmark belgium netherlands
egypt kenya india japan china korea thailand vietnam indonesia philippines peru colombia chile canada australia
walked walking ran running ate eating wrote writing sang singing swam flew flying drove driving
""".split()
STOP = set("""the of and to in a is that for it as was with be by on not he i this are or his from at which but have an had
they you were their all we can her has there been if more when will would who so no she other its may these about
them than one some what only into could out up also then do any most him my our such over such very just your
did does doing done each few how here how let me much must nor off once own same should too under until upon us via
whom why yet while where whose within without would ll ve re don didn doesn isn wasn aren weren hasn haven hadn won
""".split())

def main(path):
    words, vecs = [], []
    with gzip.open(path, 'rt', encoding='utf8') as f:
        next(f)
        for i, line in enumerate(f):
            if i >= 80000: break
            p = line.rstrip().split(' ')
            words.append(p[0]); vecs.append(np.array(p[1:], dtype=np.float32))
    allV = np.stack(vecs); pos = {w: i for i, w in enumerate(words)}
    chosen = [i for i, w in enumerate(words) if re.fullmatch('[a-z]{2,}', w)][:VOCAB]
    have = set(chosen)
    for w in EXTRA:
        if w in pos and pos[w] not in have: chosen.append(pos[w]); have.add(pos[w])
    vocab = [words[i] for i in chosen]
    V = allV[chosen]; V /= np.linalg.norm(V, axis=1, keepdims=True)

    # quantise: unit vectors have components well inside ±0.6
    SCALE = 127 / 0.6
    Q = np.clip(np.round(V * SCALE), -127, 127).astype(np.int8)
    Vq = Q.astype(np.float32) / SCALE

    # ---- 3D t-SNE of the most frequent content words ----
    mapIdx = [i for i, w in enumerate(vocab) if w not in STOP and len(w) >= 3][:MAP_WORDS]
    Y = tsne(Vq[mapIdx], dims=3, perplexity=25, iters=900)
    Y -= Y.mean(0); Y /= np.abs(Y).max()
    coords = np.zeros((len(vocab), 3), np.float32)
    coords[mapIdx] = Y
    onMap = np.zeros(len(vocab), bool); onMap[mapIdx] = True
    M = Vq[mapIdx]
    for i in np.where(~onMap)[0]:
        s = M @ Vq[i]; nn = np.argsort(-s)[:5]; wts = np.maximum(s[nn], 1e-3)
        coords[i] = (Y[nn] * wts[:, None]).sum(0) / wts.sum() + np.random.normal(0, 0.01, 3)
    C = np.clip(np.round(coords * 32000), -32767, 32767).astype('<i2')

    out = {
        'dim': V.shape[1], 'scale': SCALE, 'words': ' '.join(vocab), 'mapCount': len(mapIdx),
        'mapIndex': base64.b64encode(np.array(mapIdx, '<u2').tobytes()).decode(),
        'vectors': base64.b64encode(Q.tobytes()).decode(),
        'coords': base64.b64encode(C.tobytes()).decode(),
    }
    with open(__file__.rsplit('/', 2)[0] + '/vectors.js', 'w') as f:
        f.write('// GloVe 6B 100d (Pennington, Socher & Manning 2014; Public Domain Dedication and License).\n')
        f.write('// Generated by build/build_vectors.py: %d words, unit vectors quantised to int8, 3D t-SNE map.\n' % len(vocab))
        f.write('window.EMBED = ' + json.dumps(out) + ';\n')
    print('words', len(vocab), 'map', len(mapIdx))

def tsne(X, dims=3, perplexity=25, iters=900, seed=1):
    rng = np.random.default_rng(seed)
    n = X.shape[0]
    D = np.maximum(2 - 2 * (X @ X.T), 0).astype(np.float64)    # squared distance of unit vectors
    np.fill_diagonal(D, np.inf)
    # binary search for a beta per row so the entropy matches the perplexity
    target = np.log(perplexity); beta = np.ones(n); lo = np.zeros(n); hi = np.full(n, np.inf)
    for _ in range(60):
        Pm = np.exp(-(D - D.min(1, keepdims=True)) * beta[:, None]); Pm /= Pm.sum(1, keepdims=True)
        H = -(Pm * np.log(Pm + 1e-12)).sum(1)
        big = H > target
        lo = np.where(big, beta, lo); hi = np.where(big, hi, beta)
        beta = np.where(np.isinf(hi), beta * 2, (lo + hi) / 2)
    P = (Pm + Pm.T) / (2 * n); P = np.maximum(P, 1e-12)
    Y = rng.normal(0, 1e-4, (n, dims)); vel = np.zeros_like(Y); gains = np.ones_like(Y)
    for it in range(iters):
        exag = 12 if it < 250 else 1
        sq = (Y ** 2).sum(1); num = 1 / (1 + sq[:, None] + sq[None, :] - 2 * Y @ Y.T); np.fill_diagonal(num, 0)
        Q = np.maximum(num / num.sum(), 1e-12)
        W = (exag * P - Q) * num
        grad = 4 * ((np.diag(W.sum(1)) - W) @ Y)
        mom = 0.5 if it < 250 else 0.8
        gains = np.where(np.sign(grad) != np.sign(vel), gains + 0.2, gains * 0.8).clip(0.01)
        vel = mom * vel - 200 * gains * grad
        Y += vel; Y -= Y.mean(0)
        if it % 100 == 0: print('tsne', it, flush=True)
    return Y

if __name__ == '__main__':
    main(sys.argv[1])
